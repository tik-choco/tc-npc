const DICTS: Record<Lang, Record<MessageKey, string>> = { ja, en, zh };

export type MessageParams = Record<string, string | number>;
export type Translate = (key: MessageKey, params?: MessageParams) => string;

/** `{name}` placeholder substitution; an unknown placeholder is left as-is. */
export function translate(lang: Lang, key: MessageKey, params?: MessageParams): string {
  const template = DICTS[lang][key] ?? ja[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole,
  );
}

function isLang(value: unknown): value is Lang {
  return value === "ja" || value === "en" || value === "zh";
}

/**
 * Saved choice if there is one, otherwise the first of the browser's
 * preferred languages we actually ship (matching on the primary subtag, so
 * "zh-Hant-TW" and "en-GB" still resolve). Japanese is the fallback — it's
 * the language the app was originally written in.
 */
export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (isLang(saved)) return saved;
  } catch {
    // Ignore storage failures (private browsing, etc).
  }
  const preferred = typeof navigator === "undefined" ? [] : (navigator.languages ?? [navigator.language]);
  for (const tag of preferred) {
    const primary = String(tag ?? "").toLowerCase().split("-")[0];
    if (isLang(primary)) return primary;
  }
  return "ja";
}

let current: Lang = detectLang();
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(next: Lang): void {
  if (next === current) return;
  current = next;
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {
    // Ignore storage failures (private browsing, etc).
  }
  for (const listener of [...listeners]) listener();
}

export function subscribeLang(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}
