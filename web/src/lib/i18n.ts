// UI translations for 日本語 / English / 中文.
//
// Deliberately dependency-free, matching the app's "plain hooks only, no
// state lib" rule: a module-level current language plus a subscriber set,
// read through the useI18n() hook. The language is the user's own choice
// (設定 > 一般), seeded from the browser's languages on first visit and
// persisted in localStorage — it is NOT the same knob as `config.language`,
// which controls what language the NPC *answers* in.
//
// `ja` is the source of truth: its keys define `MessageKey`, so `en`/`zh`
// are typed as Record<MessageKey, string> and the build fails on a key that
// is added to one language but forgotten in another.

